// source local/test-env.sh door 8844; set PUBLIC_URL to the tailnet-only :8444 test proxy and OWNER_TAILSCALE_LOGIN.
// tailscale serve --bg --https=8444 http://127.0.0.1:8844; node --import tsx src/mcp/auth.e2e.ts
import assert from "node:assert/strict";
import { createHash, randomBytes } from "node:crypto";
import { readFileSync } from "node:fs";

const issuer = process.env.PUBLIC_URL!, login = process.env.OWNER_TAILSCALE_LOGIN!, home = process.env.BRAIN_HOME!;
assert(issuer?.startsWith("https://") && login && home?.startsWith("/tmp/nbrain-test/"), "Use the isolated test environment and tailnet PUBLIC_URL");
const local = "http://127.0.0.1:8844", resource = `${issuer}/mcp`;
const staticToken = readFileSync(`${home}/token`, "utf8").trim();
const noToken = await fetch(`${issuer}/mcp`, { redirect: "manual" });
assert.equal(noToken.status, 401);
const challenge = noToken.headers.get("www-authenticate")!;
assert(challenge.includes(`resource_metadata="${issuer}/.well-known/oauth-protected-resource/mcp"`));
console.log(`401 challenge: ${challenge}`);
const metadataUrl = /resource_metadata="([^"]+)"/.exec(challenge)![1]!;
const metadata = await (await fetch(metadataUrl)).json() as { resource: string; authorization_servers: string[] };
assert.equal(metadata.resource, resource);
assert.equal(metadata.authorization_servers[0], issuer);
const server = await (await fetch(`${issuer}/.well-known/oauth-authorization-server`)).json() as { registration_endpoint: string; authorization_endpoint: string; token_endpoint: string };
console.log("Discovery: protected resource → authorization server metadata OK");
const registration = await fetch(server.registration_endpoint, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ client_name: "Door Check", redirect_uris: ["https://client.example/callback"], token_endpoint_auth_method: "none", grant_types: ["authorization_code", "refresh_token"] }) });
assert.equal(registration.status, 201);
const client = await registration.json() as { client_id: string };
console.log("DCR: 201, public client registered");
const verifier = randomBytes(32).toString("base64url");
const query = new URLSearchParams({ response_type: "code", client_id: client.client_id, redirect_uri: "https://client.example/callback", resource, scope: "work life archive write", state: "door-check", code_challenge_method: "S256", code_challenge: createHash("sha256").update(verifier).digest("base64url") });
const page = await fetch(`${server.authorization_endpoint}?${query}`, { redirect: "manual" });
assert.equal(page.status, 200, "Real Tailscale proxy identity must match the configured owner");
const html = await page.text();
assert(html.includes(`<dd>${login}</dd>`), "Consent account must match the configured Tailscale owner");
assert(html.includes('value="work" checked'));
assert(!html.includes('value="life" checked'));
const nonce = /name="consent" value="([^"]+)"/.exec(html)![1]!;
const cookie = page.headers.get("set-cookie")!.split(";")[0]!;
console.log(`Owner sign-in: Tailscale-User-Login matched ${login}; consent defaults to work only`);
const spoof = await fetch(`${local}/authorize?${query}`, { headers: { "tailscale-user-login": login }, redirect: "manual" });
assert.equal(spoof.status, 403);
console.log("Direct spoofed Tailscale identity: 403, no consent");
const approved = await fetch(server.authorization_endpoint, { method: "POST", headers: { origin: issuer, cookie, "content-type": "application/x-www-form-urlencoded" }, body: new URLSearchParams({ consent: nonce, decision: "approve", scope: "work" }), redirect: "manual" });
assert.equal(approved.status, 303);
const callback = new URL(approved.headers.get("location")!);
assert.equal(callback.searchParams.get("iss"), issuer);
assert.equal(callback.searchParams.get("state"), "door-check");
console.log("Consent: 303 authorization code + matching state + issuer");
const exchange = (values: Record<string, string>) => fetch(server.token_endpoint, { method: "POST", headers: { "content-type": "application/x-www-form-urlencoded" }, body: new URLSearchParams({ client_id: client.client_id, resource, ...values }) });
const issued = await exchange({ grant_type: "authorization_code", code: callback.searchParams.get("code")!, code_verifier: verifier, redirect_uri: "https://client.example/callback" });
assert.equal(issued.status, 200);
const tokens = await issued.json() as { access_token: string; refresh_token: string; expires_in: number; scope: string };
assert.equal(tokens.scope, "work");
console.log(`Token: 200, scope=${tokens.scope}, expires_in=${tokens.expires_in}s (credentials not printed)`);
async function rpc(bearer: string, method: string, params: Record<string, unknown> = {}, base = issuer, headers: Record<string, string> = {}) {
  const response = await fetch(`${base}/mcp`, { method: "POST", headers: { authorization: `Bearer ${bearer}`, "content-type": "application/json", accept: "application/json, text/event-stream", ...headers }, body: JSON.stringify({ jsonrpc: "2.0", id: 1, method, params }) });
  assert.equal(response.status, 200, `${method} HTTP status`);
  const body = await response.json() as { error?: unknown; result?: { tools?: { name: string }[]; isError?: boolean; content?: { text?: string }[] } };
  assert(!body.error && body.result && !body.result.isError, `${method} must return a successful MCP result`);
  return body.result;
}
const tools = await rpc(tokens.access_token, "tools/list");
assert(tools.tools?.some(tool => tool.name === "memory_search"));
console.log(`OAuth tools/list: 200, ${tools.tools!.length} work-scoped tools`);
const search = await rpc(tokens.access_token, "tools/call", { name: "memory_search", arguments: { query: "nbrain", limit: 1 } });
assert(search.content?.some(part => typeof part.text === "string"));
console.log("OAuth memory_search: 200, successful real database result (content not printed)");
await rpc(staticToken, "tools/list", {}, local);
console.log("Static bearer tools/list: 200");
await rpc(staticToken, "tools/list", {}, local, { "tailscale-funnel-request": "?1" });
const entries = readFileSync(`${home}/logs/memory-mcp.log`, "utf8").trim().split("\n").map(line => JSON.parse(line) as { ip?: string; agent?: string; tool?: string });
assert(entries.some(entry => entry.ip === `tailnet:${login}` && entry.agent === "oauth-door-check" && entry.tool === "memory_search"));
const funnel401 = await fetch(`${local}/mcp`, { headers: { "tailscale-funnel-request": "?1" } });
assert.equal(funnel401.status, 401);
console.log(`Caller log: tailnet:${login}; Funnel boundary separately covered by unit test`);
const refreshed = await exchange({ grant_type: "refresh_token", refresh_token: tokens.refresh_token });
assert.equal(refreshed.status, 200);
const fresh = await refreshed.json() as { access_token: string; refresh_token: string };
assert(fresh.refresh_token !== tokens.refresh_token, "Refresh token must rotate");
await rpc(fresh.access_token, "tools/list");
console.log("Refresh: 200, rotated credentials; new access token tools/list: 200");
const reused = await exchange({ grant_type: "refresh_token", refresh_token: tokens.refresh_token });
assert.equal(reused.status, 400);
assert.equal((await reused.json() as { error: string }).error, "invalid_grant");
assert.equal((await fetch(`${issuer}/mcp`, { headers: { authorization: `Bearer ${fresh.access_token}` } })).status, 401);
console.log("Old refresh replay: 400 invalid_grant; grant revoked, new access token: 401");
console.log("OAuth end-to-end: PASS; no credentials printed");
